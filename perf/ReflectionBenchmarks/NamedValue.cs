namespace ReflectionBenchmarks;

public static class NamedValue
{
    public static NamedValue<T> Create<T>(T? value, string? displayText) => new(value, displayText);
}

public sealed class NamedValue<T>
{
    public T Value;
    public string? DisplayText { get; set; }

    public NamedValue(T? value, string? displayText)
    {
        Value = value!;
        DisplayText = displayText;
    }

    public override string? ToString() => DisplayText
        ?? Value?.ToString()
        ?? BenchmarkDotNet.Parameters.ParameterInstance.NullParameterTextRepresentation;

    // This doesn't work with the code generated by BenchmarkDotNet.
    //public static implicit operator T?(NamedValue<T> @this) => @this.Value;
}
